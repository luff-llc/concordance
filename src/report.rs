use crate::{fail, Catalog, Entry, Result, Status};

fn table(value: &str) -> String {
    value.replace('|', "\\|").replace(['\n', '\r'], " ")
}

impl Catalog {
    pub fn report(&self) -> Result<String> {
        let config = &self.config.report;
        let (base, target) = (&config.baseline, &config.target);
        let (bl, tl) = (config.label(base), config.label(target));
        for entry in self.entries.values() {
            if !entry.platforms.contains_key(base) || !entry.platforms.contains_key(target) {
                return fail(format!(
                    "{}: report requires {base} and {target} statuses",
                    entry.id
                ));
            }
        }
        let baseline: Vec<_> = self
            .entries
            .values()
            .filter(|e| e.platforms[base].status == Status::Shipped)
            .collect();
        let counts = |entries: &[&Entry]| -> [usize; 4] {
            [
                Status::Shipped,
                Status::Partial,
                Status::Missing,
                Status::NotApplicable,
            ]
            .map(|s| {
                entries
                    .iter()
                    .filter(|e| e.platforms[target].status == s)
                    .count()
            })
        };
        let totals = counts(&baseline);
        let has_na = totals[3] != 0;
        let mut summary = format!(
            "**{} {bl} capabilities: {} {tl} shipped, {} partial, {} missing",
            baseline.len(),
            totals[0],
            totals[1],
            totals[2]
        );
        if has_na {
            summary.push_str(&format!(", {} not-applicable", totals[3]));
        }
        summary.push_str(".**");
        let mut lines = vec![
            format!("# {}", config.title),
            String::new(),
            "Generated by `concordance report`. Edit the catalog, then regenerate.".into(),
            String::new(),
            config.intro.trim_end().into(),
            String::new(),
            summary,
            String::new(),
            format!(
                "| Area | Entries | {bl} baseline | {tl} shipped | Partial | Missing |{}",
                if has_na { " Not applicable |" } else { "" }
            ),
            format!(
                "| --- | ---: | ---: | ---: | ---: | ---: |{}",
                if has_na { " ---: |" } else { "" }
            ),
        ];
        for (area, file) in &self.area_files {
            let group: Vec<_> = self
                .entries
                .values()
                .filter(|e| self.areas[&e.id] == *area)
                .collect();
            let included: Vec<_> = group
                .iter()
                .copied()
                .filter(|e| e.platforms[base].status == Status::Shipped)
                .collect();
            let c = counts(&included);
            lines.push(format!(
                "| [{area}]({file}) | {} | {} | {} | {} | {} |{}",
                group.len(),
                included.len(),
                c[0],
                c[1],
                c[2],
                if has_na {
                    format!(" {} |", c[3])
                } else {
                    String::new()
                }
            ));
        }
        lines.extend([
            format!(
                "| **Total** | **{}** | **{}** | **{}** | **{}** | **{}** |{}",
                self.entries.len(),
                baseline.len(),
                totals[0],
                totals[1],
                totals[2],
                if has_na {
                    format!(" **{}** |", totals[3])
                } else {
                    String::new()
                }
            ),
            String::new(),
            "## Ten highest-impact gaps".into(),
            String::new(),
            config.ordering_note.trim_end().into(),
            String::new(),
        ]);
        let mut gaps: Vec<_> = baseline
            .iter()
            .copied()
            .filter(|e| e.platforms[target].status.is_gap())
            .collect();
        gaps.sort_by_key(|e| self.gap_key(e));
        for (index, entry) in gaps.iter().take(10).enumerate() {
            let p = &entry.platforms[target];
            lines.push(format!(
                "{}. **{}** — `{}` ({}, {}): {}",
                index + 1,
                entry.title,
                entry.id,
                entry.impact.as_str(),
                p.status.as_str(),
                p.gap.as_deref().unwrap_or("No gap recorded.")
            ));
        }
        for (status, heading) in [
            (Status::Missing, "Missing capabilities, by user impact"),
            (Status::Partial, "Partial capabilities, by user impact"),
        ] {
            lines.extend([
                String::new(),
                format!("## {heading}"),
                String::new(),
                "| Impact | ID | Capability | Gap |".into(),
                "| --- | --- | --- | --- |".into(),
            ]);
            for entry in &gaps {
                let p = &entry.platforms[target];
                if p.status == status {
                    lines.push(format!(
                        "| {} | `{}` | {} | {} |",
                        entry.impact.as_str(),
                        entry.id,
                        table(&entry.title),
                        table(p.gap.as_deref().unwrap_or("No gap recorded."))
                    ));
                }
            }
        }
        let extras: Vec<_> = self
            .entries
            .values()
            .filter(|e| e.platforms[base].status != Status::Shipped)
            .collect();
        if !extras.is_empty() {
            // A partial baseline is not an adaptation; keep that distinction visible.
            let adaptations_only = extras
                .iter()
                .all(|e| e.platforms[base].status == Status::NotApplicable);
            lines.extend([String::new(), if adaptations_only { format!("## {tl}-specific adaptations") } else { "## Outside the shipped baseline".into() }, String::new(), if adaptations_only { format!("These entries have no {bl} counterpart and are excluded from the {bl} parity totals.") } else { format!("These entries are not shipped on {bl} and are excluded from its parity totals.") }, String::new()]);
            for entry in extras {
                let extra = config
                    .adaptation_platform
                    .as_ref()
                    .map(|p| {
                        format!(
                            "; {} {}",
                            config.label(p),
                            entry
                                .platforms
                                .get(p)
                                .map(|p| p.status.as_str())
                                .unwrap_or("not recorded")
                        )
                    })
                    .unwrap_or_default();
                lines.push(format!(
                    "- `{}`: {tl} {}{extra}. {}",
                    entry.id,
                    entry.platforms[target].status.as_str(),
                    entry.summary
                ));
            }
        }
        lines.extend([String::new(), "## Evidence limits".into(), String::new(), format!("- {bl} entries without linked tests: {}.", baseline.iter().filter(|e| e.platforms[base].tests.is_empty()).count()), format!("- {tl} shipped/partial entries without linked tests: {}.", baseline.iter().filter(|e| matches!(e.platforms[target].status, Status::Shipped | Status::Partial) && e.platforms[target].tests.is_empty()).count()), format!("- {}", config.evidence_note), "- See [README](README.md) for status rules, exclusions, source roots, and audit limitations.".into(), String::new()]);
        Ok(lines.join("\n"))
    }
}
