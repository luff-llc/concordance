use crate::{fail, Catalog, Result};
use std::collections::BTreeSet;
use std::fs::{self, OpenOptions};
use std::io::Write;
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Language {
    Kotlin,
    Swift,
}
#[derive(Debug, Default)]
pub struct JourneyResult {
    pub created: Vec<PathBuf>,
    pub unchanged: Vec<PathBuf>,
    /// Existing files with different contents are always preserved, even generated ones.
    pub preserved: Vec<PathBuf>,
}

// Encode separators distinctly: a.b-c and a-b.c must never collide.
fn symbol(id: &str) -> String {
    format!("entry_{}", id.replace('-', "_h_").replace('.', "_d_"))
}
fn comment(value: &str) -> String {
    value.replace('\r', "").replace('\n', "\n        // ")
}
fn literal(value: &str, language: Language) -> String {
    let mut out = String::from("\"");
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '$' if language == Language::Kotlin => out.push_str("\\$"),
            c if c.is_control() || c == '\u{2028}' || c == '\u{2029}' => match language {
                Language::Kotlin => out.push_str(&format!("\\u{:04x}", c as u32)),
                Language::Swift => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
            },
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
fn package_text(package: Option<&str>, language: Language) -> Result<String> {
    let Some(package) = package else {
        return Ok(String::new());
    };
    if language != Language::Kotlin {
        return fail("--package applies only to Kotlin");
    }
    if package.split('.').any(|part| {
        part.is_empty()
            || !part
                .bytes()
                .enumerate()
                .all(|(i, c)| c.is_ascii_alphabetic() || c == b'_' || (i > 0 && c.is_ascii_digit()))
    }) {
        return fail("invalid Kotlin package name");
    }
    // Backticks allow keywords such as `in` in otherwise valid package segments.
    Ok(format!(
        "package {}\n\n",
        package
            .split('.')
            .map(|p| format!("`{p}`"))
            .collect::<Vec<_>>()
            .join(".")
    ))
}

impl Catalog {
    /// One constant per stable entry ID. Its value is the explicit accessibility
    /// identifier when recorded, otherwise the stable ID (a proposed identifier).
    pub fn identifiers(&self, language: Language, package: Option<&str>) -> Result<String> {
        let mut out = String::from("// Generated by concordance ids. Do not edit.\n");
        out.push_str(&package_text(package, language)?);
        out.push_str(match language {
            Language::Kotlin => "object CatalogIds {\n",
            Language::Swift => "public enum CatalogIds {\n",
        });
        for entry in self.entries.values() {
            let explicit = !entry.accessibility.identifier.is_empty();
            let value = if explicit {
                &entry.accessibility.identifier
            } else {
                &entry.id
            };
            out.push_str(&format!(
                "    // {}{}\n",
                entry.id,
                if explicit {
                    ""
                } else {
                    " — proposed identifier; none recorded in source"
                }
            ));
            out.push_str(&format!(
                "    {} {} = {}\n",
                match language {
                    Language::Kotlin => "const val",
                    Language::Swift => "public static let",
                },
                symbol(&entry.id),
                literal(value, language)
            ));
        }
        out.push_str("}\n");
        Ok(out)
    }

    /// Create one test class per entry; never truncate or overwrite any existing file.
    pub fn journeys(&self, language: Language, directory: &Path) -> Result<JourneyResult> {
        fs::create_dir_all(directory)?;
        let mut result = JourneyResult::default();
        // Case-insensitive filesystems must also have unique names.
        let mut names = BTreeSet::new();
        for entry in self.entries.values() {
            let name = format!("Catalog_{}", symbol(&entry.id));
            if !names.insert(name.to_lowercase()) {
                return fail(format!("generated filename collision: {name}"));
            }
            let extension = if language == Language::Kotlin {
                "kt"
            } else {
                "swift"
            };
            let path = directory.join(format!("{name}Tests.{extension}"));
            let mut out = format!("// Generated by concordance journeys for {}.\n// TODO: implement native setup, actions, and assertions. Existing files are preserved.\n", entry.id);
            match language {
                Language::Kotlin => out.push_str(&format!("import androidx.compose.ui.test.junit4.createComposeRule\nimport org.junit.Ignore\nimport org.junit.Rule\nimport org.junit.Test\n\nclass {name}Tests {{\n    @get:Rule\n    val compose = createComposeRule()\n")),
                Language::Swift => out.push_str(&format!("import XCTest\n\nfinal class {name}Tests: XCTestCase {{\n")),
            }
            for (index, journey) in entry.acceptance.iter().enumerate() {
                match language {
                    Language::Kotlin => out.push_str(&format!("\n    @Ignore(\"TODO: implement acceptance journey\")\n    @Test\n    fun journey_{}() {{\n", index + 1)),
                    Language::Swift => out.push_str(&format!("\n    func testJourney_{}() throws {{\n", index + 1)),
                }
                for (label, value) in [
                    ("Given", &journey.given),
                    ("When", &journey.when),
                    ("Then", &journey.then),
                ] {
                    out.push_str(&format!("        // {label}: {}\n", comment(value)));
                }
                out.push_str(match language {
                    Language::Kotlin => "        TODO(\"Wire the real app and assert the behavior with Compose UI tests\")\n",
                    Language::Swift => "        throw XCTSkip(\"TODO: launch the real app and assert the behavior\")\n",
                });
                out.push_str("    }\n");
            }
            out.push_str("}\n");
            match OpenOptions::new().write(true).create_new(true).open(&path) {
                Ok(mut file) => {
                    file.write_all(out.as_bytes())?;
                    result.created.push(path);
                }
                Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => {
                    if fs::read_to_string(&path)? == out {
                        result.unchanged.push(path);
                    } else {
                        result.preserved.push(path);
                    }
                }
                Err(error) => return Err(error.into()),
            }
        }
        Ok(result)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn identifier_encoding_is_unambiguous() {
        assert_ne!(symbol("a.b-c"), symbol("a-b.c"));
        assert_ne!(symbol("a.b"), symbol("a-b.c"));
    }
    #[test]
    fn native_literals_escape_interpolation_and_controls() {
        assert_eq!(
            literal("$x\\(name)\n\"\u{0}", Language::Kotlin),
            "\"\\$x\\\\(name)\\n\\\"\\u0000\""
        );
        assert_eq!(
            literal("$x\\(name)\n\"\u{0}", Language::Swift),
            "\"$x\\\\(name)\\n\\\"\\u{0}\""
        );
        assert!(package_text(Some("a; import b"), Language::Kotlin).is_err());
        assert!(package_text(Some("app"), Language::Swift).is_err());
    }
}
