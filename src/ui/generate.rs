use std::fs::{self, OpenOptions};
use std::io::Write;
use std::path::Path;

// Names contain neither underscores nor capitals, so separator encoding is injective.
fn symbol(name: &str) -> String {
    name.replace('-', "_h_").replace('.', "_d_")
}
fn preserve(path: &Path, text: &str, result: &mut JourneyResult) -> Result<()> {
    match OpenOptions::new().write(true).create_new(true).open(path) {
        Ok(mut file) => {
            file.write_all(text.as_bytes())?;
            result.created.push(path.to_path_buf());
        }
        Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {
            if fs::read_to_string(path)? == text {
                result.unchanged.push(path.to_path_buf());
            } else {
                result.preserved.push(path.to_path_buf());
            }
        }
        Err(e) => return Err(e.into()),
    }
    Ok(())
}
fn comment(text: &str) -> String {
    text.chars()
        .map(|c| {
            if c.is_control() || matches!(c, '\u{2028}' | '\u{2029}') {
                ' '
            } else {
                c
            }
        })
        .collect()
}
impl Tokens {
    /// Generate native roles. Artwork rules require the app's own palette resolver.
    pub fn native(&self, language: Language) -> Result<String> {
        self.validate()?;
        let swift = language == Language::Swift;
        let mut out = if swift {
            "// Generated by concordance tokens. Existing files are preserved.\nimport SwiftUI\nimport UIKit\n\npublic enum DesignTokens {\n".to_owned()
        } else {
            "// Generated by concordance tokens. Existing files are preserved.\nimport androidx.compose.foundation.isSystemInDarkTheme\nimport androidx.compose.runtime.Composable\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.text.TextStyle\nimport androidx.compose.ui.text.font.FontWeight\nimport androidx.compose.ui.unit.dp\nimport androidx.compose.ui.unit.sp\nimport androidx.compose.animation.core.AnimationSpec\nimport androidx.compose.animation.core.spring\nimport androidx.compose.animation.core.tween\n\nobject DesignTokens {\n".to_owned()
        };
        for (name, color) in &self.colors {
            let n = symbol(name);
            if let Some(rule) = &color.rule {
                out.push_str(&format!("    // Artwork rule ({name}): {}. Values below are fallbacks; resolve in the app.\n", comment(rule)));
            }
            if swift {
                let [r, g, b] = rgb(&color.light)?.map(|c| c / 255.0);
                let [dr, dg, db] = rgb(&color.dark)?.map(|c| c / 255.0);
                out.push_str(&format!("    public static let color_{n}_light = Color(red: {r}, green: {g}, blue: {b})\n    public static let color_{n}_dark = Color(red: {dr}, green: {dg}, blue: {db})\n    public static let color_{n} = Color(uiColor: UIColor {{ traits in\n        traits.userInterfaceStyle == .dark ? UIColor(red: {dr}, green: {dg}, blue: {db}, alpha: 1) : UIColor(red: {r}, green: {g}, blue: {b}, alpha: 1)\n    }})\n"));
            } else {
                out.push_str(&format!("    val color_{n}_light = Color(0xFF{})\n    val color_{n}_dark = Color(0xFF{})\n    val color_{n}: Color @Composable get() = if (isSystemInDarkTheme()) color_{n}_dark else color_{n}_light\n", &color.light[1..], &color.dark[1..]));
            }
        }
        for (name, style) in &self.typography {
            let n = symbol(name);
            if swift {
                // A computed property re-evaluates the preferred content-size category.
                out.push_str(&format!("    public static var type_{n}: Font {{ Font(UIFontMetrics(forTextStyle: .{}).scaledFont(for: UIFont.systemFont(ofSize: {}, weight: UIFont.Weight(rawValue: {})))) }}\n    public static let type_{n}_size: CGFloat = {}\n    public static let type_{n}_lineHeight: CGFloat = {}\n", style.dynamic_type, style.size, swift_weight(style.weight), style.size, style.line_height));
            } else {
                out.push_str(&format!("    // {} on iOS; sp follows the Android font scale.\n    val type_{n} = TextStyle(fontSize = {}.sp, lineHeight = {}.sp, fontWeight = FontWeight({}))\n", style.dynamic_type, style.size, style.line_height, style.weight));
            }
        }
        for (category, values) in [("spacing", &self.spacing), ("radius", &self.radii)] {
            for (name, value) in values {
                let n = symbol(name);
                out.push_str(&if swift {
                    format!("    public static let {category}_{n}: CGFloat = {value}\n")
                } else {
                    format!("    val {category}_{n} = {value}.dp\n")
                });
            }
        }
        for (name, material) in &self.materials {
            let n = symbol(name);
            if swift {
                out.push_str(&format!("    public static let material_{n}: Material = .{}\n    public static let material_{n}_elevation: CGFloat = {}\n    public static let material_{n}_blur: CGFloat = {}\n    public static let material_{n}_opacity: Double = {}\n", material.swift, material.elevation, material.blur, material.opacity));
            } else {
                out.push_str(&format!("    // Native counterpart to SwiftUI {}: apply surface, blur and shadow in the app.\n    val material_{n}_elevation = {}.dp\n    val material_{n}_blur = {}.dp\n    const val material_{n}_opacity = {}f\n", material.swift, material.elevation, material.blur, material.opacity));
            }
        }
        for (name, motion) in &self.motions {
            let n = symbol(name);
            let value = match (swift, motion) {
                (
                    true,
                    Motion {
                        duration: Some(d), ..
                    },
                ) => format!("Animation.easeInOut(duration: {d})"),
                (
                    true,
                    Motion {
                        response: Some(r),
                        damping: Some(d),
                        ..
                    },
                ) => format!("Animation.spring(response: {r}, dampingFraction: {d})"),
                (
                    false,
                    Motion {
                        duration: Some(d), ..
                    },
                ) => format!("tween(durationMillis = {})", (d * 1000.0).round() as u64),
                (
                    false,
                    Motion {
                        response: Some(r),
                        damping: Some(d),
                        ..
                    },
                ) => format!(
                    "spring(dampingRatio = {d}f, stiffness = {}f)",
                    (std::f64::consts::TAU / r).powi(2)
                ),
                _ => unreachable!("validated motion"),
            };
            out.push_str(&if swift {
                format!("    public static let motion_{n}: Animation = {value}\n")
            } else {
                format!("    val motion_{n}: AnimationSpec<Float> = {value}\n")
            });
        }
        out.push_str("}\n");
        Ok(out)
    }
    pub fn write_native(&self, language: Language, path: &Path) -> Result<JourneyResult> {
        let mut result = JourneyResult::default();
        preserve(path, &self.native(language)?, &mut result)?;
        Ok(result)
    }
}

fn css_name(category: &str, name: &str) -> String {
    format!("--{category}-{}", name.replace('.', "-"))
}
fn css_number(value: f64) -> String {
    value.to_string()
}
impl Tokens {
    /// Generate one CSS file of custom properties. `source` names the catalog in the header.
    pub fn css(&self, source: &str) -> Result<String> {
        self.validate()?;
        let mut seen = std::collections::BTreeSet::new();
        let mut declare = |property: String| -> Result<String> {
            if !seen.insert(property.clone()) {
                return Err(format!("CSS custom property collision: {property}").into());
            }
            Ok(property)
        };
        let source = comment(source).replace("*/", "* /");
        let mut root = String::new();
        let (mut light, mut dark) = (Vec::new(), Vec::new());
        for (name, color) in &self.colors {
            let property = declare(css_name("color", name))?;
            if let Some(rule) = &color.rule {
                let rule = comment(rule).replace("*/", "* /");
                let rule = rule.trim_end_matches('.');
                root.push_str(&format!("  /* Artwork rule ({name}): {rule}. Values are fallbacks; resolve in the app. */\n"));
            }
            let (l, d) = (color.light.to_lowercase(), color.dark.to_lowercase());
            root.push_str(&format!("  {property}: {l};\n"));
            light.push((property.clone(), l));
            dark.push((property, d));
        }
        for (name, style) in &self.typography {
            let base = css_name("type", name);
            for suffix in ["size", "line-height", "weight"] {
                declare(format!("{base}-{suffix}"))?;
            }
            root.push_str(&format!(
                "  {base}-size: {}px;\n  {base}-line-height: {}px;\n  {base}-weight: {};\n  /* Skipped: {base} dynamic_type ({}) has no CSS form. */\n",
                css_number(style.size),
                css_number(style.line_height),
                style.weight,
                style.dynamic_type
            ));
        }
        for (category, values) in [("spacing", &self.spacing), ("radius", &self.radii)] {
            for (name, value) in values {
                let property = declare(css_name(category, name))?;
                root.push_str(&format!("  {property}: {}px;\n", css_number(*value)));
            }
        }
        for (name, material) in &self.materials {
            let base = css_name("material", name);
            for suffix in ["elevation", "blur", "opacity"] {
                declare(format!("{base}-{suffix}"))?;
            }
            root.push_str(&format!(
                "  {base}-elevation: {}px;\n  {base}-blur: {}px;\n  {base}-opacity: {};\n  /* Skipped: {base} swift material ({}) has no CSS form. */\n",
                css_number(material.elevation),
                css_number(material.blur),
                css_number(material.opacity),
                comment(&material.swift).replace("*/", "* /")
            ));
        }
        for (name, motion) in &self.motions {
            let property = declare(css_name("motion", name))?;
            match motion.duration {
                Some(d) => root.push_str(&format!("  {property}: {}ms;\n", (d * 1000.0).round() as u64)),
                None => root.push_str(&format!("  /* Skipped: {property} is a spring (response and damping) with no CSS form. */\n")),
            }
        }
        let mut out = format!("/* Generated by concordance tokens from {source}. Existing files are preserved. */\n:root {{\n{root}}}\n");
        if !self.colors.is_empty() {
            let block = |values: &[(String, String)], indent: &str| -> String {
                values
                    .iter()
                    .map(|(p, v)| format!("{indent}{p}: {v};\n"))
                    .collect()
            };
            out.push_str(&format!("@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme=\"light\"]) {{\n{}  }}\n}}\n", block(&dark, "    ")));
            out.push_str(&format!(
                ":root[data-theme=\"dark\"] {{\n{}}}\n",
                block(&dark, "  ")
            ));
            out.push_str(&format!(
                ":root[data-theme=\"light\"] {{\n{}}}\n",
                block(&light, "  ")
            ));
        }
        Ok(out)
    }
    pub fn write_css(&self, source: &str, path: &Path) -> Result<JourneyResult> {
        let mut result = JourneyResult::default();
        preserve(path, &self.css(source)?, &mut result)?;
        Ok(result)
    }
}
fn swift_weight(weight: u16) -> f64 {
    match weight {
        1..=149 => -0.8,
        150..=249 => -0.6,
        250..=349 => -0.4,
        350..=449 => 0.0,
        450..=549 => 0.23,
        550..=649 => 0.3,
        650..=749 => 0.4,
        750..=849 => 0.56,
        _ => 0.62,
    }
}
impl UiCatalog {
    /// All required screen/state pairs, whether or not evidence exists yet.
    pub fn capture_plan(&self, platform: &str) -> Result<String> {
        self.require_platform(platform)?;
        Ok(self
            .screens
            .values()
            .flat_map(|screen| {
                screen
                    .states
                    .keys()
                    .map(move |state| format!("{}\t{state}\n", screen.id))
            })
            .collect())
    }
    /// Create skipped native tests for missing PNG/JSON pairs only; preserve edits.
    pub fn capture_stubs(
        &self,
        platform: &str,
        language: Language,
        captures: &Path,
        out: &Path,
    ) -> Result<JourneyResult> {
        self.require_platform(platform)?;
        fs::create_dir_all(out)?;
        let mut result = JourneyResult::default();
        for screen in self.screens.values() {
            for state in screen.states.keys() {
                let stem = format!("{}.{state}.{platform}", screen.id);
                if reference(captures, &format!("{stem}.png"))?.is_file()
                    && reference(captures, &format!("{stem}.json"))?.is_file()
                {
                    continue;
                }
                let n = format!(
                    "Capture_{}_{}_{}",
                    symbol(&screen.id),
                    symbol(state),
                    symbol(platform)
                );
                let comments = format!("// Generated by concordance capture-plan. Existing files are preserved.\n// TODO: launch {} in state {state}; freeze fixtures, time and animations.\n// Save {stem}.png and {stem}.json in the capture directory.\n// JSON: width/height in pixels, scale, nodes in anatomy preorder; logical frames,\n// identifier, component role, text_size for typography, resolved_color for artwork rules.\n// Required anatomy: {}\n", screen.id, screen.regions().iter().map(|r| r.id.as_str()).collect::<Vec<_>>().join(", "));
                let (extension, body) = match language {
                    Language::Swift => ("swift", format!("import XCTest\n\nfinal class {n}: XCTestCase {{\n    func testCapture() throws {{\n        // TODO: XCUIApplication().screenshot().pngRepresentation; export accessibility frames.\n        throw XCTSkip(\"TODO: implement native capture and snapshot export\")\n    }}\n}}\n")),
                    Language::Kotlin => ("kt", format!("import androidx.compose.ui.test.junit4.createComposeRule\nimport org.junit.Ignore\nimport org.junit.Rule\nimport org.junit.Test\n\nclass {n} {{\n    @get:Rule val compose = createComposeRule()\n    @Ignore(\"TODO: implement native capture and snapshot export\")\n    @Test fun capture() {{\n        // TODO: onRoot().captureToImage(); export semantics identifiers and bounds.\n        TODO(\"Capture the real app and write PNG plus JSON\")\n    }}\n}}\n")),
                };
                preserve(
                    &out.join(format!("{n}.{extension}")),
                    &(comments + &body),
                    &mut result,
                )?;
            }
        }
        Ok(result)
    }
}
